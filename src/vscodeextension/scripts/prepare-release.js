'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const extensionDir = path.resolve(__dirname, '..');
const repoRoot = path.resolve(extensionDir, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, 'package.json'), 'utf8'));
const read = relative => fs.readFileSync(path.join(repoRoot, relative), 'utf8');

// Follow the installed production closure, including transitive Lezer packages.
const dependencyEntries = dependencies => Object.entries(dependencies).map(([name, spec]) => ({
  name,
  packageName: spec.startsWith('npm:') ? spec.slice(4, spec.lastIndexOf('@')) : name,
}));
const pending = dependencyEntries(manifest.dependencies).map(entry => ({ ...entry, from: extensionDir }));
const packages = new Map();
while (pending.length) {
  const { name, packageName, from } = pending.pop();
  let directory = path.dirname(require.resolve(name, { paths: [from] }));
  let dependency;
  while (true) {
    const file = path.join(directory, 'package.json');
    if (fs.existsSync(file)) {
      const candidate = JSON.parse(fs.readFileSync(file, 'utf8'));
      if (candidate.name === packageName) {
        dependency = candidate;
        break;
      }
    }
    const parent = path.dirname(directory);
    if (parent === directory) throw new Error(`Cannot locate package metadata for ${name}`);
    directory = parent;
  }
  if (packages.has(directory)) continue;
  packages.set(directory, dependency);
  for (const entry of dependencyEntries(dependency.dependencies || {})) {
    pending.push({ ...entry, from: directory });
  }
}

const dependencyNotices = [...packages.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([directory, dependency]) => {
    const notices = fs.readdirSync(directory).filter(file =>
      /^(?:licen[cs]e|copying|copyright|.*notice)/i.test(file) &&
      fs.statSync(path.join(directory, file)).isFile());
    if (!notices.some(file => /^(?:licen[cs]e|copying)/i.test(file))) {
      throw new Error(`No license file found for ${dependency.name}`);
    }
    return `${dependency.name}@${dependency.version} (${dependency.license})\n` +
      notices.map(file => `  ${path.relative(extensionDir, path.join(directory, file)).split(path.sep).join('/')}`).join('\n');
  }).join('\n\n');

const inputs = ['NOTICE', 'AUTHOR', 'src/vscodeextension/src/LICENSE',
  'src/web_visualizer/LICENSE', 'src/web_visualizer/src/highlightjs/LICENSE',
  'src/web_visualizer/src/highlightjs/styles/LICENSE', 'COPYING'];
const license = 'Generated by scripts/prepare-release.js; edit the original notice/license inputs.\n\n' +
  inputs.map(file => `===== ${file} =====\n\n${read(file).trim()}\n`).join('\n') +
  '\n===== Runtime dependency licenses and notices =====\n\n' +
  'The following original files accompany the runtime packages in this VSIX.\n' +
  'They are preserved verbatim, including TypeScript third-party notices.\n\n' + dependencyNotices + '\n';

const releaseDir = path.join(extensionDir, 'release');
const sourceDir = path.join(extensionDir, 'source');
fs.mkdirSync(releaseDir, { recursive: true });
fs.mkdirSync(sourceDir, { recursive: true });
for (const file of [path.join(repoRoot, 'LICENSE'), path.join(extensionDir, 'LICENSE'),
  path.join(releaseDir, 'LICENSE')]) {
  fs.writeFileSync(file, license);
}
fs.writeFileSync(path.join(releaseDir, 'version'), manifest.version + '\n');

// Exclude generated outputs and installed dependencies, not original build inputs.
const archive = path.join(sourceDir, `source-code-visualizer-${manifest.version}.tar.gz`);
const excludes = ['*/node_modules', '*/out', '*/release', '*/__pycache__', '*.pyc',
  '*/.vscode-test', '*/.DS_Store', 'src/vscodeextension/source',
  'src/vscodeextension/media/web_visualizer.js', 'src/vscodeextension/media/web_visualizer.css',
  'src/vscodeextension/media/web_visualizer_version', 'src/vscodeextension/media/LICENSE'];
execFileSync('tar', [...excludes.map(pattern => `--exclude=${pattern}`),
  '-czf', archive, '-C', repoRoot, 'src', 'package.json', 'README.MD',
  'LICENSE', 'COPYING', 'NOTICE', 'AUTHOR', 'docs/architecture-and-development.md'],
  { stdio: 'inherit', env: { ...process.env, COPYFILE_DISABLE: '1' } });
console.log(`Prepared notices for ${packages.size} runtime packages and ${path.relative(extensionDir, archive)}`);
